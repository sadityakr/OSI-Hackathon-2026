"""Write a side-by-side markdown comparison of two arms (default bare vs skill) for human evaluation.

Scores say how often an arm matched the answer key; a researcher evaluating the skill also needs to read what each
arm actually said. This script puts the two reports for every case next to each other, with the automatic grades,
so a collaborator can judge quality, correctness of caveats and usefulness of the questions themselves.

Input:
    eval/runs/<run>/<arm>/<case>/report.json (and judge.json for interpretation cases) for the two arms.
Process:
    Interpretation reports: judge score and per-item grades, summary, observations, caveats, questions, citations.
    Identification reports: top candidates, peaks with irreps and patterns, properties, verdict, limits.
Output:
    results/<run>/COMPARISON_<armA>_vs_<armB>.md
"""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def load(p):
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def bullets(items, limit=12):
    items = items or []
    out = [f"- {str(i)}" for i in items[:limit]]
    if len(items) > limit:
        out.append(f"- ... ({len(items) - limit} more)")
    return out or ["- (none)"]


def interpret_block(arm, rep, judge):
    lines = [f"#### {arm}"]
    if rep is None:
        return lines + ["(no report)"]
    if judge and "score" in judge:
        lines.append(f"**Judge score {judge['score']:.2f}**, citation specificity {judge.get('citation_specificity')}, "
                     f"wrong claims made: {', '.join(judge.get('wrong_claims_made', [])) or 'none'}")
        lines.append("Rubric items: " + ", ".join(f"{g['id']}={g['met']}" for g in judge["grades"]["items"]))
    lines += ["", f"*Summary:* {rep.get('summary', '')}", "", "*Observations:*"]
    lines += bullets([f"{o['finding']} [{o['provenance']}] (evidence: {o['evidence']}; source: {o.get('source')})"
                      for o in rep.get("observations", [])])
    lines += ["", "*Caveats:*"] + bullets(rep.get("caveats"))
    lines += ["", "*Questions for the user:*"] + bullets(rep.get("questions_for_user"))
    lines += ["", "*Properties:*"] + bullets([f"{p['name']} = {p['value']} [{p['provenance']}] ({p.get('source')})"
                                              for p in rep.get("properties", [])])
    lines += ["", "*Citations:*"] + bullets(rep.get("citations"))
    return lines


def identify_block(arm, rep):
    lines = [f"#### {arm}"]
    if rep is None:
        return lines + ["(no report)"]
    lines.append("*Candidates:* " + "; ".join(f"{c['material']} ({c['confidence']})" for c in rep["candidates"][:3]))
    if rep.get("hint_verdict") != "not_applicable":
        lines.append(f"*Hint verdict:* {rep['hint_verdict']}: {rep.get('hint_reasoning', '')}")
    lines += ["", "*Peaks:*"] + bullets([f"{p['position_cm1']} cm-1: {p['assignment']} / irrep {p['irrep']} / "
                                         f"pattern {p['pattern']} [{p['provenance']}]" for p in rep["peaks"]], 15)
    lines += ["", "*Properties:*"] + bullets([f"{p['name']} = {p['value']} ({p.get('source')})"
                                              for p in rep.get("properties", [])])
    lines += ["", "*Limits:*"] + bullets(rep.get("limits"), 6)
    return lines


def main():
    ap = argparse.ArgumentParser(description="Side-by-side comparison of two arms of a run, for human evaluation.")
    ap.add_argument("run", help="run name under eval/runs/")
    ap.add_argument("--arms", nargs=2, default=["bare", "skill"], help="the two arms to compare")
    args = ap.parse_args()
    run = ROOT / "eval" / "runs" / args.run
    a, b = args.arms
    cases = sorted({p.name for arm in (a, b) for p in (run / arm).glob("*") if p.is_dir()})
    lines = [f"# {args.run}: {a} vs {b}", "",
             f"Generated by `eval/compare_arms.py`. Model and cost per case: `usage.json` in each case folder. "
             f"Case inputs: `data/test_set/<split>/<case>/input.json`.", ""]
    for c in cases:
        ra, rb = load(run / a / c / "report.json"), load(run / b / c / "report.json")
        lines += ["---", f"## {c}", ""]
        interp = (ra or rb or {}).get("summary") is not None
        for arm, rep in ((a, ra), (b, rb)):
            lines += (interpret_block(arm, rep, load(run / arm / c / "judge.json")) if interp
                      else identify_block(arm, rep)) + [""]
    out = ROOT / "results" / args.run / f"COMPARISON_{a}_vs_{b}.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"{out.relative_to(ROOT)}: {len(cases)} cases")


if __name__ == "__main__":
    main()
